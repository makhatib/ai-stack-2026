#!/usr/bin/env bash
# AI Stack 2026 — runtime per-image facts.  THE AUTHORITATIVE MEASUREMENT.
#
# `probe-images.sh` reports what a shell sees with the entrypoint REPLACED,
# which bypasses any privilege drop the entrypoint performs.  This script asks
# the question that actually matters, of the RUNNING container: what uid/gid is
# PID 1, and did `read_only: true` actually hold?
#
# Run it against a live stack:  aistack up && scripts/probe-runtime.sh
# It merges `runtime_uid`, `runtime_gid` and `read_only_ok` into
# config/image-facts.yaml.
set -euo pipefail
ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
FACTS="$ROOT/config/image-facts.yaml"
OUT="$ROOT/config/runtime-facts.yaml"

{
  printf '# AI Stack 2026 — RUNTIME facts.  Measured against running containers.\n'
  printf '# Generated by scripts/probe-runtime.sh on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '#\n'
  printf '# runtime_uid/gid: the ids of PID 1 INSIDE the running container, read\n'
  printf '# from /proc/1/status. This is the field the exceptions register and the\n'
  printf '# secret file modes are argued from — NOT image-facts.yaml shell_uid.\n'
  printf '#\n'
  printf '# read_only_ok: whether the root filesystem is genuinely read-only, tested\n'
  printf '# by attempting a write. A `read_only: true` that the service works around\n'
  printf '# with a writable mount is not the property we claim.\n'
  printf 'schema: aistack.runtime-facts.v1\n'
  printf 'probed_at: "%s"\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf 'services:\n'
} > "$OUT"

for c in $(docker ps --format '{{.Names}}' | grep '^aistack-' | sort); do
  svc="${c#aistack-}"
  uid=""; gid=""; ro="unknown"; method=""

  # /proc/1/status needs no shell in the container when read through docker
  # exec of a shell — but several images have no shell, so fall back to the
  # daemon's own view, which needs nothing inside the container at all.
  if out="$(docker exec "$c" cat /proc/1/status 2>/dev/null)"; then
    uid="$(printf '%s' "$out" | awk '/^Uid:/{print $2}')"
    gid="$(printf '%s' "$out" | awk '/^Gid:/{print $2}')"
    method="proc-1-status"
  else
    # Config.User is metadata, and the daemon does not expose the effective
    # id of PID 1. Say which one we got rather than presenting them alike.
    uid="$(docker inspect "$c" --format '{{.Config.User}}' 2>/dev/null)"
    method="config-user-metadata-only"
  fi

  if docker exec "$c" sh -c 'touch /.aistack-ro-probe 2>/dev/null && rm -f /.aistack-ro-probe' >/dev/null 2>&1; then
    ro="false   # WRITE SUCCEEDED — read_only is not in force for this container"
  elif docker exec "$c" true >/dev/null 2>&1; then
    ro="true"
  else
    ro="unknown  # no shell in image; not measured"
  fi

  {
    printf '  %s:\n' "$svc"
    printf '    runtime_uid: %s\n' "${uid:-null}"
    printf '    runtime_gid: %s\n' "${gid:-null}"
    printf '    method: %s\n' "$method"
    printf '    read_only_ok: %s\n' "$ro"
  } >> "$OUT"
done

echo "wrote $OUT"
echo
echo "Any 'runs as root' argument in security-exceptions.yaml must cite"
echo "runtime_uid from THIS file, not shell_uid from image-facts.yaml."
