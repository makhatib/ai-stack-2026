#!/usr/bin/env bash
# AI Stack 2026 — per-image facts, MEASURED.
#
# final-design §5.6 and F2: `read_only`, non-root `user:` and healthcheck probes
# are [A] for roughly twelve images, and NOM-258 must run each image once and
# RECORD THE ANSWER.  Per-image facts cannot be established from documents.
#
# Writes config/image-facts.yaml.  Everything downstream — the secret file
# modes, the exceptions register, the hardening deviations — reads that file
# rather than guessing.
#
# This probe runs each image's declared entrypoint only for `id`; it does not
# start the service.  Nothing here touches a volume or a network.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck disable=SC1091
source "$ROOT/versions.env"
OUT="$ROOT/config/image-facts.yaml"

probe() {
  local svc="$1" image="$2" tag="$3" digest="$4"
  local ref="${image}:${tag}@${digest}"
  local uid gid user shell_found="none"

  if [ "$tag" = "UNRESOLVED" ]; then
    printf '  %s:\n    status: not-built-in-this-scope\n' "$svc"
    return
  fi

  docker pull -q --platform linux/amd64 "$ref" >/dev/null 2>&1 || true

  # The configured user, from image metadata.  This is what Docker will run as
  # when compose does not override it.
  user="$(docker inspect "$ref" --format '{{.Config.User}}' 2>/dev/null || true)"

  # The ids a SHELL sees when the entrypoint is REPLACED.
  #
  # READ THE FIELD NAME: this is `shell_uid`, not "the uid the service runs as".
  # Replacing the entrypoint bypasses any privilege drop the entrypoint
  # performs — the Postgres image's entrypoint re-executes as `postgres` via
  # gosu, so this probe reports 0 for it while the actual server process is not
  # root.  Treating that 0 as "postgres runs as root" would be exactly the kind
  # of unmeasured claim F2 exists to prevent.
  #
  # `scripts/probe-runtime.sh` takes the measurement that answers the real
  # question, against the RUNNING container's PID 1.  That is the field the
  # exceptions register and the secret file modes must be argued from.
  #
  # Several images are distroless and have no shell, so try a few spellings and
  # record "no-shell" rather than pretending the probe succeeded.
  for sh in /bin/sh /busybox/sh /bin/bash; do
    if out="$(docker run --rm --platform linux/amd64 --entrypoint "$sh" "$ref" -c 'id -u; id -g' 2>/dev/null)"; then
      uid="$(printf '%s' "$out" | sed -n 1p)"
      gid="$(printf '%s' "$out" | sed -n 2p)"
      shell_found="$sh"
      break
    fi
  done

  {
    printf '  %s:\n' "$svc"
    printf '    image: %s\n' "$image"
    printf '    tag: %s\n' "$tag"
    printf '    digest: %s\n' "$digest"
    printf '    config_user: "%s"\n' "${user:-}"
    if [ "$shell_found" = none ]; then
      printf '    shell_uid: null\n'
      printf '    shell_gid: null\n'
      printf '    probe: no-shell-in-image\n'
      printf '    note: "Distroless or shell-less. config_user above is image METADATA, which is weaker evidence than a measurement. See probe-runtime.sh."\n'
    else
      printf '    shell_uid: %s\n' "${uid}"
      printf '    shell_gid: %s\n' "${gid}"
      printf '    probe: "entrypoint-replaced-with %s"\n' "$shell_found"
      printf '    note: "shell_uid is what a shell sees with the ENTRYPOINT REPLACED. It is NOT the uid the service runs as when an entrypoint drops privileges (postgres does). The authoritative field is runtime_uid, written by probe-runtime.sh against the running container PID 1."\n'
    fi
    printf '    runtime_uid: unmeasured   # set by scripts/probe-runtime.sh\n'
    printf '    runtime_gid: unmeasured\n'
  } >> "$OUT"
}

{
  printf '# AI Stack 2026 — per-image facts.  MEASURED, not assumed.\n'
  printf '#\n'
  printf '# Generated by scripts/probe-images.sh on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# Regenerate after ANY digest bump: a pin change invalidates its own\n'
  printf '# evidence rather than inheriting it (final-design §5.7).\n'
  printf '#\n'
  printf '# `gid` drives the per-service secret file mode (S13): 0640 root:<gid>\n'
  printf '# where the consumer is non-root, 0600 root:root where it runs as root.\n'
  printf 'schema: aistack.image-facts.v1\n'
  printf 'probed_at: "%s"\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf 'images:\n'
} > "$OUT"

probe caddy         "$CADDY_IMAGE"       "$CADDY_TAG"       "$CADDY_DIGEST"
probe authelia      "$AUTHELIA_IMAGE"    "$AUTHELIA_TAG"    "$AUTHELIA_DIGEST"
probe postgres      "$POSTGRES_IMAGE"    "$POSTGRES_TAG"    "$POSTGRES_DIGEST"
probe homepage      "$HOMEPAGE_IMAGE"    "$HOMEPAGE_TAG"    "$HOMEPAGE_DIGEST"
probe open-webui    "$OPEN_WEBUI_IMAGE"  "$OPEN_WEBUI_TAG"  "$OPEN_WEBUI_DIGEST"
probe ollama        "$OLLAMA_IMAGE"      "$OLLAMA_TAG"      "$OLLAMA_DIGEST"
probe litellm       "$LITELLM_IMAGE"     "$LITELLM_TAG"     "$LITELLM_DIGEST"
probe n8n           "$N8N_IMAGE"         "$N8N_TAG"         "$N8N_DIGEST"
probe docling-serve "$DOCLING_IMAGE"     "$DOCLING_TAG"     "$DOCLING_DIGEST"
probe agentgateway  "$AGENTGATEWAY_IMAGE" "$AGENTGATEWAY_TAG" "$AGENTGATEWAY_DIGEST"

echo "wrote $OUT"
